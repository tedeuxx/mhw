#!/usr/bin/python3
# Clipboard guard (ADR-0011): watch the macOS pasteboard and catch employer/client terms, credentials
# and personal data in what is copied, before it is pasted into any prompt.
#
#   clipboard_guard.py watch [--config FILE]   the background watcher (run by the LaunchAgent)
#   clipboard_guard.py add-term [--config FILE] add one term to the hashed list, typed at the terminal
#   clipboard_guard.py check-config [--config FILE]  print the effective non-secret settings
#
# Properties this file must keep, each with a test in clipboard_guard_test.py:
#   - it writes NOTHING except the clipboard (when told to) and the term list (add-term only):
#     no log, no history, no cache, no record of what matched (ADR-0005);
#   - a notice names categories and the mitigation, never the content or the matched term;
#   - an item marked concealed, transient or auto-generated (nspasteboard.org) is never read past its
#     type list, so a password-manager copy never reaches the detector;
#   - the term list holds salted hashes of normalised terms, never plaintext, and add-term reads the
#     term from the terminal with echo off: never from argv, the environment or a pipe.
#
# Standard library only. Runs on the Command Line Tools python3 (3.9) and later.
import hashlib
import hmac
import os
import re
import secrets
import subprocess
import sys
import time
import unicodedata

PROJECT = "personal-multi-harness-workstation-configuration"
SKIP_TYPES = (
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
)
# Qt applications (KeePassXC, read in its source 2026-10-01) declare the marker as the MIME name
# "application/x-nspasteboard-concealed-type". Whether Qt turns that into the exact UTI above or into a
# Qt-generated type name was NOT established, so any type whose name carries the marker is skipped too.
# Erring toward skipping costs one unchecked item; erring the other way can redact a copied password.
SKIP_SUBSTRINGS = ("nspasteboard-concealed", "nspasteboard-transient", "nspasteboard-autogenerated")
TEXT_TYPE = "public.utf8-plain-text"
MAX_TERM_TOKENS = 6
MIN_TERM_CHARS = 3
TERMS_HEADER = "# %s clipboard terms v1: HMAC-SHA256(salt, normalised term), one per line; never plaintext\n" % PROJECT

