class MacPasteboard:
    """NSPasteboard through the Objective-C runtime with ctypes (no third-party module). `name` selects
    a private named pasteboard (tests); None is the general pasteboard (the watcher)."""

    def __init__(self, name=None):
        import ctypes
        self.c = ctypes
        self.objc = ctypes.cdll.LoadLibrary("/usr/lib/libobjc.A.dylib")
        ctypes.cdll.LoadLibrary("/System/Library/Frameworks/AppKit.framework/AppKit")
        self.objc.objc_getClass.restype = ctypes.c_void_p
        self.objc.objc_getClass.argtypes = [ctypes.c_char_p]
        self.objc.sel_registerName.restype = ctypes.c_void_p
        self.objc.sel_registerName.argtypes = [ctypes.c_char_p]
        with self._pool():
            cls = self._cls("NSPasteboard")
            if name is None:
                pb = self._send(ctypes.c_void_p, cls, "generalPasteboard")
            else:
                pb = self._send(ctypes.c_void_p, cls, "pasteboardWithName:", (ctypes.c_void_p, self._ns(name)))
            self.pb = self._send(ctypes.c_void_p, pb, "retain")

    def _cls(self, name):
        return self.objc.objc_getClass(name.encode())

    def _send(self, restype, obj, sel, *args):
        c = self.c
        fn = c.CFUNCTYPE(restype, c.c_void_p, c.c_void_p, *[a[0] for a in args])(("objc_msgSend", self.objc))
        return fn(obj, self.objc.sel_registerName(sel.encode()), *[a[1] for a in args])

    def _ns(self, s):
        return self._send(self.c.c_void_p, self._cls("NSString"), "stringWithUTF8String:",
                          (self.c.c_char_p, s.encode("utf-8")))

    def _py(self, ns):
        if not ns:
            return None
        return self.c.string_at(self._send(self.c.c_void_p, ns, "UTF8String")).decode("utf-8", "replace")

    def _pool(self):
        outer = self

        class Pool:
            def __enter__(self):
                c = outer.c
                self.p = outer._send(c.c_void_p, outer._send(c.c_void_p, outer._cls("NSAutoreleasePool"), "alloc"), "init")

            def __exit__(self, *exc):
                outer._send(None, self.p, "drain")
        return Pool()

    def change_count(self):
        with self._pool():
            return self._send(self.c.c_long, self.pb, "changeCount")

    def types(self):
        c = self.c
        with self._pool():
            arr = self._send(c.c_void_p, self.pb, "types")
            if not arr:
                return []
            n = self._send(c.c_ulong, arr, "count")
            return [self._py(self._send(c.c_void_p, arr, "objectAtIndex:", (c.c_ulong, i))) for i in range(n)]

    def string(self):
        with self._pool():
            return self._py(self._send(self.c.c_void_p, self.pb, "stringForType:", (self.c.c_void_p, self._ns(TEXT_TYPE))))

    def put(self, items):
        """Replace the whole item (every flavour) with {type: string}."""
        c = self.c
        with self._pool():
            self._send(c.c_long, self.pb, "clearContents")
            for t, s in items.items():
                self._send(c.c_bool, self.pb, "setString:forType:", (c.c_void_p, self._ns(s)), (c.c_void_p, self._ns(t)))

    def set_string(self, s):
        self.put({TEXT_TYPE: s})

    def clear(self):
        with self._pool():
            self._send(self.c.c_long, self.pb, "clearContents")

    def release(self):
        """Destroy a private named pasteboard (tests)."""
        with self._pool():
            self._send(None, self.pb, "releaseGlobally")

# ----------------------------------------------------------------------------------- the watcher


def is_marked(type_name):
    """True for a password-manager marker: the nspasteboard.org UTIs, or a type name carrying one."""
    low = (type_name or "").lower()
    return type_name in SKIP_TYPES or any(s in low for s in SKIP_SUBSTRINGS)


class Guard:
    def __init__(self, conf, pasteboard, notifier, salts):
        self.conf = conf
        self.pb = pasteboard
        self.notifier = notifier
        self.salts = salts
        self.salt = None
        self.terms = frozenset()
        self.terms_stamp = None
        self.warned_no_salt = False

    def refresh_terms(self):
        """Re-read the term list when it changes, so a term added while the watcher runs counts at once."""
        try:
            st = os.stat(self.conf["terms_file"])
            stamp = (st.st_mtime_ns, st.st_size)
        except OSError:
            stamp = None
        if stamp == self.terms_stamp:
            return
        self.terms_stamp = stamp
        self.terms = read_terms(self.conf["terms_file"])
        if self.terms and not self.salt:
            self.salt = self.salts.get()
            if not self.salt and not self.warned_no_salt:
                self.warned_no_salt = True
                self.notifier.notify("notice_no_salt")

    def check(self, change_count):
        """Check the item at change_count once. Returns what happened, for tests; keeps nothing."""
        if any(is_marked(t) for t in self.pb.types()):
            return "skipped-marked"
        text = self.pb.string()
        if text is None:
            return "no-text"
        if len(text.encode("utf-8")) > int(self.conf["max_bytes"]):
            self.notifier.notify("notice_too_large", max=self.conf["max_bytes"])
            return "too-large"
        self.refresh_terms()
        spans = find_spans(text, self.terms, self.salt)
        if not spans:
            return "clean"
        cats = ", ".join(categories(spans))
        choice = "clean" if self.conf["mode"] == "sanitise" else self.notifier.offer(categories(spans))
        if choice == "keep":
            return "kept"
        if self.pb.change_count() != change_count:
            self.notifier.notify("notice_changed", categories=cats)
            return "changed"
        if choice == "clear":
            self.pb.clear()
            self.notifier.notify("notice_cleared", categories=cats)
            return "cleared"
        self.pb.set_string(sanitise(text, spans))
        self.notifier.notify("notice_cleaned", categories=cats)
        return "cleaned"

    def run(self, max_cycles=None):
        last = None
        cycles = 0
        while max_cycles is None or cycles < max_cycles:
            cycles += 1
            try:
                cc = self.pb.change_count()
                if cc != last:
                    self.check(cc)
                    last = self.pb.change_count()
            except Exception as exc:  # a crash would end the watch silently; report the class only,
                # because an exception's message can quote the input. Mark the item seen so one bad
                # item yields one notice, not one per poll.
                last = self._safe_count(last)
                self.notifier.notify("notice_error", error=type(exc).__name__)
            time.sleep(int(self.conf["poll_seconds"]))

    def _safe_count(self, fallback):
        try:
            return self.pb.change_count()
        except Exception:
            return fallback

